const RECOVERABLE_PREVIEW_IMPERSONATION_CODES = new Set([
  "IMPERSONATION_LEASE_NOT_FOUND",
  "IMPERSONATION_LEASE_REVOKED",
  "IMPERSONATION_LEASE_EXPIRED",
  "IMPERSONATION_LEASE_MISMATCH",
  "IMPERSONATION_TARGET_INACTIVE",
  "WRONG_TOURNAMENT",
]);

export function isRecoverablePreviewImpersonationCode(value) {
  return RECOVERABLE_PREVIEW_IMPERSONATION_CODES.has(String(value || "").trim().toUpperCase());
}
